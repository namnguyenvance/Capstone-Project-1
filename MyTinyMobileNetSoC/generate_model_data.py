#!/usr/bin/env python3
"""
Generate C source/header files from quantized TFLite model.
============================================================

Extracts weights, biases, and exact quantization parameters 
for EACH layer by parsing TFLite execution plan.
"""

import struct
import numpy as np
import os
import sys

try:
    import tensorflow as tf
except ImportError:
    print("ERROR: tensorflow is required. Install with: pip install tensorflow")
    sys.exit(1)

def compute_quantized_multiplier_and_shift(real_multiplier):
    if real_multiplier == 0:
        return 0, 0
    import math
    shift = 0
    significand = real_multiplier
    while significand < 0.5:
        significand *= 2.0
        shift -= 1
    while significand >= 1.0:
        significand /= 2.0
        shift += 1
    quantized_multiplier = int(round(significand * (1 << 31)))
    if quantized_multiplier >= (1 << 31):
        quantized_multiplier = (1 << 31) - 1
    right_shift = -shift
    return quantized_multiplier, right_shift

def generate_c_array(name, values, c_type, per_line=16):
    arr_str = f"const {c_type} {name}[{len(values)}] = {{\n    "
    for i, val in enumerate(values):
        arr_str += f"{val}, "
        if (i + 1) % per_line == 0:
            arr_str += "\n    "
    arr_str = arr_str.rstrip(", \n ") + "\n};\n\n"
    return arr_str

def generate_dims_array(name, dims):
    vals = ", ".join(str(d) for d in dims)
    return f"const int {name}[] = {{{vals}}};\n\n"

def main():
    TFLITE_MODEL = "tinymobilenet_mnist_quant.tflite"
    OUTPUT_C = "tinymobilenet_model_data.c"
    OUTPUT_H = "tinymobilenet_model_data.h"

    if not os.path.exists(TFLITE_MODEL):
        print(f"ERROR: {TFLITE_MODEL} not found!")
        sys.exit(1)

    print(f"Loading {TFLITE_MODEL}...")
    interpreter = tf.lite.Interpreter(model_path=TFLITE_MODEL)
    interpreter.allocate_tensors()

    tensor_details = interpreter.get_tensor_details()
    ops = interpreter._get_ops_details()

    layer_configs = [
        ("tmn_conv0", "CONV_2D"),
        ("tmn_dw1",   "DEPTHWISE_CONV_2D"),
        ("tmn_pw1",   "CONV_2D"),
        ("tmn_dw2",   "DEPTHWISE_CONV_2D"),
        ("tmn_pw2",   "CONV_2D"),
        ("tmn_dw3",   "DEPTHWISE_CONV_2D"),
        ("tmn_pw3",   "CONV_2D"),
        ("tmn_gap",   "MEAN"),
        ("tmn_dense", "FULLY_CONNECTED"),
    ]

    target_ops = []
    for op in ops:
        if op['op_name'] in [c[1] for c in layer_configs]:
            target_ops.append(op)

    print(f"Found {len(target_ops)} target ops in TFLite model.")

    with open(OUTPUT_C, "w") as fc, open(OUTPUT_H, "w") as fh:
        fc.write("/* Auto-generated by generate_model_data.py */\n")
        fc.write("#define TINYMOBILENET_RUN\n")
        fc.write('#include "tinymobilenet_model_data.h"\n\n')
        
        fh.write("/* Auto-generated by generate_model_data.py */\n")
        fh.write("#ifndef TINYMOBILENET_MODEL_DATA_H\n")
        fh.write("#define TINYMOBILENET_MODEL_DATA_H\n")
        fh.write("#include <stdint.h>\n\n")

        for i, (prefix, expected_type) in enumerate(layer_configs):
            op = target_ops[i]
            
            in_tensor_idx = op['inputs'][0]
            if expected_type in ["CONV_2D", "DEPTHWISE_CONV_2D", "FULLY_CONNECTED"]:
                weight_idx = op['inputs'][1]
                bias_idx = op['inputs'][2] if len(op['inputs']) > 2 else -1
            else:
                weight_idx = -1
                bias_idx = -1

            out_tensor_idx = op['outputs'][0]

            in_tensor = tensor_details[in_tensor_idx]
            out_tensor = tensor_details[out_tensor_idx]

            in_scale = in_tensor['quantization'][0]
            in_zp = in_tensor['quantization'][1]
            out_scale = out_tensor['quantization'][0]
            out_zp = out_tensor['quantization'][1]

            fc.write(f"/* ===== {prefix} ({expected_type}) ===== */\n")
            
            fc.write(f"const int32_t {prefix}_input_offset = {-in_zp};\n")
            fc.write(f"const int32_t {prefix}_output_offset = {out_zp};\n\n")
            fh.write(f"extern const int32_t {prefix}_input_offset;\n")
            fh.write(f"extern const int32_t {prefix}_output_offset;\n")

            if expected_type == "MEAN":
                mult = in_scale / out_scale
                qm, qs = compute_quantized_multiplier_and_shift(mult)
                fc.write(f"const int32_t {prefix}_output_multiplier = {qm};\n")
                fc.write(f"const int8_t {prefix}_output_shift = {qs};\n\n")
                fh.write(f"extern const int32_t {prefix}_output_multiplier;\n")
                fh.write(f"extern const int8_t {prefix}_output_shift;\n\n")
                continue

            weight_tensor = tensor_details[weight_idx]
            k_data = interpreter.get_tensor(weight_idx)
            k_shape = weight_tensor['shape']
            
            quant_params = weight_tensor.get('quantization_parameters', {})
            w_scales = quant_params.get('scales', [])
            if len(w_scales) == 0:
                w_scales = [weight_tensor['quantization'][0]]
            
            multipliers = []
            shifts = []
            for ws in w_scales:
                effective_mult = (in_scale * ws) / out_scale
                qm, qs = compute_quantized_multiplier_and_shift(effective_mult)
                multipliers.append(qm)
                shifts.append(qs)
            
            if expected_type == "FULLY_CONNECTED":
                fc.write(f"const int32_t {prefix}_output_multiplier = {multipliers[0]};\n")
                fc.write(f"const int8_t {prefix}_output_shift = {shifts[0]};\n")
                fh.write(f"extern const int32_t {prefix}_output_multiplier;\n")
                fh.write(f"extern const int8_t {prefix}_output_shift;\n")
            else:
                fc.write(generate_c_array(f"{prefix}_output_multiplier", multipliers, "int32_t"))
                fc.write(generate_c_array(f"{prefix}_output_shift", shifts, "int8_t"))
                fh.write(f"extern const int32_t {prefix}_output_multiplier[{len(multipliers)}];\n")
                fh.write(f"extern const int8_t {prefix}_output_shift[{len(shifts)}];\n")

            # Weights
            if expected_type == "DEPTHWISE_CONV_2D":
                k_transposed = np.transpose(k_data[0], (2, 0, 1)) if len(k_shape)==4 else k_data
                num_channels = k_transposed.shape[0]
                kernel_h = k_transposed.shape[1]
                kernel_w = k_transposed.shape[2]
                fc.write(generate_dims_array(f"{prefix}_kernel_dims", [kernel_w, kernel_h, num_channels]))
                fc.write(generate_c_array(f"{prefix}_kernel_data", k_transposed.flatten().tolist(), "int8_t"))
                fh.write(f"extern const int {prefix}_kernel_dims[3];\n")
                fh.write(f"extern const int8_t {prefix}_kernel_data[{k_transposed.size}];\n")
            elif expected_type == "FULLY_CONNECTED":
                fc.write(generate_dims_array(f"{prefix}_weight_dims", list(k_shape)))
                fc.write(generate_c_array(f"{prefix}_weight_data", k_data.flatten().tolist(), "int8_t"))
                fh.write(f"extern const int {prefix}_weight_dims[2];\n")
                fh.write(f"extern const int8_t {prefix}_weight_data[{k_data.size}];\n")
            else:
                k_transposed = np.transpose(k_data, (0, 3, 1, 2)) if len(k_shape)==4 else k_data
                out_ch = k_shape[0]
                in_ch = k_shape[3]
                kh = k_shape[1]
                kw = k_shape[2]
                fc.write(generate_dims_array(f"{prefix}_kernel_dims", [kw, kh, in_ch, out_ch]))
                fc.write(generate_c_array(f"{prefix}_kernel_data", k_transposed.flatten().tolist(), "int8_t"))
                fh.write(f"extern const int {prefix}_kernel_dims[4];\n")
                fh.write(f"extern const int8_t {prefix}_kernel_data[{k_transposed.size}];\n")

            if bias_idx != -1:
                b_data = interpreter.get_tensor(bias_idx)
                fc.write(generate_dims_array(f"{prefix}_bias_dims", list(tensor_details[bias_idx]['shape'])))
                fc.write(generate_c_array(f"{prefix}_bias_data", b_data.flatten().tolist(), "int32_t"))
                fh.write(f"extern const int {prefix}_bias_dims[{len(b_data.shape)}];\n")
                fh.write(f"extern const int32_t {prefix}_bias_data[{b_data.size}];\n")
            
            fc.write("\n")
            fh.write("\n")

        fh.write("#endif /* TINYMOBILENET_MODEL_DATA_H */\n")

    print("Success! generate_model_data.py updated headers and C files.")

if __name__ == "__main__":
    main()
